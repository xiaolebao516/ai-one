export type WorkbenchTextKey = Key;

export interface WorkbenchText {
  zh: boolean;
  t: (key: Key, values?: Record<string, string | number>) => string;
}

function fill(template: string, values?: Record<string, string | number>): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

export function workbenchText(locale: Locale): WorkbenchText {
  const zh = hudLocale(locale) === 'zh';
  return { zh, t: (key, values) => fill((zh ? ZH : EN)[key], values) };
}
